          return true;
        }
        final double? n = _parseLen(v);
        if (n == null || n <= 0) {
          return false;
        }
        col.width = n;
      case 'col.align':
        final ReportTextAlign? a = reportEnumByName(ReportTextAlign.values, v);
        if (a == null) {
          return false;
        }
        col.align = a;
      case 'cell.field':
        cell.field = _opt(v);
      case 'cell.text':
        cell.text = v.isEmpty ? null : v;
      case 'cell.format':
        cell.format = _opt(v);
      case 'cell.bold':
        cell.bold = _parseBool(v);
      case 'foot.text':
        while (e.footerCells.length <= i) {
          e.footerCells.add(ReportTableCell(text: ''));
        }
        e.footerCells[i]
          ..field = null
          ..text = v;
      default:
        return false;
    }
    return true;
  }

  bool _applyBand(ReportBand b, String key, String v) {
    switch (key) {
      case 'height':
        final double? n = _parseLen(v);
        if (n == null || n < 0) {
          return false;
        }
        b.height = _round(n);
      case 'background':
        b.background = _opt(v);
      case 'visibleWhen':
        b.visibleWhen = _opt(v);
      case 'dataSet':
        b.dataSet = _opt(v);
      case 'rowHeight':
        if (v.trim().isEmpty) {
          b.rowHeight = null;
          return true;
        }
        final double? n = _parseLen(v);
        if (n == null || n <= 0) {
          return false;
        }
        b.rowHeight = n;
      case 'sortBy':
        final String? s = _opt(v);
        if (s != null) {
          try {
            for (final ({String source, bool? descending}) k
                in ReportExpression.sortKeys(s)) {
              ReportExpression.parse(k.source);
            }
          } on ReportExpressionException {
            return false;
          }
        }
        b.sortBy = s;
      case 'sortDescending':
        b.sortDescending = _parseBool(v);
      case 'filter':
        b.filter = _opt(v);
      case 'groupBy':
        b.groupBy = _opt(v);
      case 'printOnFirstPage':
        b.printOnFirstPage = _parseBool(v);
      case 'printOnLastPage':
        b.printOnLastPage = _parseBool(v);
      case 'newPageBefore':
        b.newPageBefore = _parseBool(v);
      case 'newPageAfter':
        b.newPageAfter = _parseBool(v);
      case 'keepTogether':
        b.keepTogether = _parseBool(v);
      case 'repeatOnEveryPage':
        b.repeatOnEveryPage = _parseBool(v);
      default:
        return false;
    }
    return true;
  }

  bool _applyReport(String key, String v) {
    final ReportTemplate t = _template;
    if (key.startsWith('margin.')) {
      final double? n = _parseLen(v);
      if (n == null || n < 0) {
        return false;
      }
      switch (key) {
        case 'margin.top':
          t.margins.top = n;
        case 'margin.bottom':
          t.margins.bottom = n;
        case 'margin.left':
          t.margins.left = n;
        case 'margin.right':
          t.margins.right = n;
        default:
          return false;
      }
      return true;
    }
    if (key == 'var+') {
      _newVariable(t);
      return true;
    }
    if (key == 'color+') {
      final int eq = v.indexOf('=');
      if (eq <= 0) {
        return false;
      }
      final String name = v.substring(0, eq).trim();
      final String value = v.substring(eq + 1).trim();
      if (name.isEmpty) {
        return false;
      }
      if (ReportColor.tryParse(value) == null) {
        return false;
      }
      t.colors[name] = value;
      return true;
    }
    if (key.startsWith('color.')) {
      final String name = key.substring(6);
      if (v.trim().isEmpty) {
        return t.colors.remove(name) != null;
      }
      if (ReportColor.tryParse(v) == null) {
        return false;
      }
      t.colors[name] = v.trim();
      return true;
    }
    if (key.startsWith('var.')) {
      return _applyVariable(t, key, v);
    }
    switch (key) {
      case 'name':
        if (v.trim().isEmpty) {
          return false;
        }
        t.name = v.trim();
      case 'isRtl':
        t.isRtl = _parseBool(v);
      case 'mirrorRtl':
        t.mirrorRtl = _parseBool(v);
      case 'defaultFont':
        t.defaultFont = v.trim();
      case 'defaultFontSize':
        final double? n = _parseNum(v);
        if (n == null || n <= 0) {
          return false;
        }
        t.defaultFontSize = n;
      case 'unit':
        final ReportUnit? u = reportEnumByName(ReportUnit.values, v);
        if (u == null) {
          return false;
        }
        t.unit = u;
      case 'pageSize':
        final ReportPageSize? s = ReportPageSize.byName(v);
        if (s == null) {
          return false;
        }
        t.pageSize = s;
      case 'orientation':
        final ReportOrientation? o = reportEnumByName(
          ReportOrientation.values,
          v,
        );
        if (o == null) {
          return false;
        }
        t.orientation = o;
      case 'coordinateOrigin':
        final ReportCoordinateOrigin? o = reportEnumByName(
          ReportCoordinateOrigin.values,
          v,
        );
        if (o == null) {
          return false;
        }
        t.coordinateOrigin = o;
      default:
        return false;
    }
    return true;
  }

