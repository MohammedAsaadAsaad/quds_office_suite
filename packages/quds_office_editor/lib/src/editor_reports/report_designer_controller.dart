  /// Deletes the selected elements.
  void deleteSelection() {
    final List<String> ids = List<String>.of(_selection);
    if (ids.isEmpty) {
      return;
    }
    _mutate(() {
      var any = false;
      for (final String id in ids) {
        final (ReportBand, ReportElement)? found = _template.findElement(id);
        if (found != null) {
          found.$1.elements.remove(found.$2);
          any = true;
        }
      }
      return any;
    });
    _selection.clear();
    notifyListeners();
  }

  /// Copies the selection to the designer clipboard.
  void copySelection() {
    final List<ReportElement> sel = selectedElements;
    if (sel.isEmpty) {
      return;
    }
    _clipboard = <ReportElement>[for (final ReportElement e in sel) e.clone()];
    _clipboardBand = _template.findElement(sel.first.id)?.$1.kind;
    notifyListeners();
  }

  /// Copies then deletes the selection.
  void cutSelection() {
    copySelection();
    deleteSelection();
  }

  /// Whether [paste] has something to insert.
  bool get canPaste => _clipboard.isNotEmpty;

  /// Pastes clipboard elements into the selected band (or their source
  /// band), offset so they do not hide the originals.
  void paste() {
    if (_clipboard.isEmpty) {
      return;
    }
    final ReportBand? target =
        (_selectedBand == null ? null : _template.band(_selectedBand!)) ??
        (_clipboardBand == null ? null : _template.band(_clipboardBand!)) ??
        (_template.bands.isEmpty ? null : _template.bands.first);
    if (target == null) {
      return;
    }
    final List<ReportElement> pasted = <ReportElement>[
      for (final ReportElement e in _clipboard) e.clone(),
    ];
    _mutate(() {
      final bool sameBand = target.kind == _clipboardBand;
      for (final ReportElement e in pasted) {
        if (sameBand) {
          e
            ..x = e.x + 4
            ..y = e.y + 4;
        }
        target.elements.add(e);
      }
      return true;
    });
    _clipboard = <ReportElement>[
      for (final ReportElement e in pasted) e.clone(),
    ];
    _clipboardBand = target.kind;
    _selection
      ..clear()
      ..addAll(pasted.map((ReportElement e) => e.id));
    _selectedBand = target.kind;
    notifyListeners();
  }

  /// Duplicates the selection in place (offset by 4 pt).
  void duplicateSelection() {
    final List<ReportElement> keep = List<ReportElement>.of(_clipboard);
    final ReportBandKind? keepBand = _clipboardBand;
    copySelection();
    paste();
    _clipboard = keep;
    _clipboardBand = keepBand;
  }

  /// Moves the selection to the end of its band (painted last).
  void bringToFront() => _reorder(front: true);

  /// Moves the selection to the start of its band (painted first).
  void sendToBack() => _reorder(front: false);

  void _reorder({required bool front}) {
    final List<ReportElement> sel = selectedElements;
    if (sel.isEmpty) {
      return;
    }
    _mutate(() {
      for (final ReportElement e in sel) {
        final ReportBand band = _template.findElement(e.id)!.$1;
        band.elements.remove(e);
        if (front) {
          band.elements.add(e);
        } else {
          band.elements.insert(0, e);
        }
      }
      return true;
    });
  }

  /// Adds a band of [kind] (no-op when present) and selects it.
  void addBand(ReportBandKind kind) {
    if (_template.band(kind) != null) {
      selectBand(kind);
      return;
    }
    _mutate(() {
      final ReportBand band = _template.ensureBand(
        kind,
        height: 20 * 72 / 25.4,
      );
      if (kind == ReportBandKind.groupHeader) {
        band.groupBy = 'item.category';
      }
      return true;
    });
    selectBand(kind);
  }

  /// Removes the band of [kind] with its elements.
  void removeBand(ReportBandKind kind) {
    final ReportBand? band = _template.band(kind);
    if (band == null) {
      return;
    }
    _mutate(() => _template.bands.remove(band));
    _selection.removeWhere((String id) => _template.findElement(id) == null);
    if (_selectedBand == kind) {
      _selectedBand = null;
    }
    notifyListeners();
  }

  /// Appends a column to table [id].
  void addTableColumn(String id) {
    final ReportElement? e = _template.findElement(id)?.$2;
    if (e is! ReportTableElement) {
      return;
    }
    _mutate(() {
      _resizeColumns(e, e.columns.length + 1);
      return true;
    });
  }

  /// Removes column [index] of table [id].
  void removeTableColumn(String id, int index) {
    final ReportElement? e = _template.findElement(id)?.$2;
    if (e is! ReportTableElement ||
        index < 0 ||
        index >= e.columns.length ||
        e.columns.length <= 1) {
      return;
    }
    _mutate(() {
      e.columns.removeAt(index);
      if (index < e.cells.length) {
        e.cells.removeAt(index);
      }
      if (index < e.footerCells.length) {
        e.footerCells.removeAt(index);
      }
      return true;
    });
  }

  void _resizeColumns(ReportTableElement e, int count) {
    final int n = count < 1 ? 1 : count;
    while (e.columns.length < n) {
      final int i = e.columns.length + 1;
      e.columns.add(
        ReportTableColumn(header: _template.isRtl ? 'عمود $i' : 'Column $i'),
      );
    }
    while (e.cells.length < n) {
      e.cells.add(ReportTableCell(field: 'item.field${e.cells.length + 1}'));
    }
    while (e.columns.length > n) {
      e.columns.removeLast();
    }
    while (e.cells.length > n) {
      e.cells.removeLast();
    }
    if (e.footerCells.isNotEmpty) {
      while (e.footerCells.length < n) {
        e.footerCells.add(ReportTableCell(text: ''));
      }
      while (e.footerCells.length > n) {
        e.footerCells.removeLast();
      }
    }
  }

  // ------------------------------------------------------------ history

  /// Whether [undo] has a step.
  bool get canUndo => _undo.isNotEmpty;

  /// Whether [redo] has a step.
  bool get canRedo => _redo.isNotEmpty;

  /// Reverts the last change.
  void undo() {
    _endEdits();
    if (_undo.isEmpty) {
      return;
    }
    _redo.add(_snapshot());
    _restore(_undo.removeLast());
  }

  /// Re-applies the last undone change.
  void redo() {
    _endEdits();
    if (_redo.isEmpty) {
      return;
    }
    _undo.add(_snapshot());
    _restore(_redo.removeLast());
  }

  _Snapshot _snapshot() =>
      _Snapshot(_template.copy(), List<String>.of(_selection), _selectedBand);

  void _restore(_Snapshot s) {
    _template = s.template.copy();
    _selection
      ..clear()
      ..addAll(
        s.selection.where((String id) => _template.findElement(id) != null),
      );
    _selectedBand = s.band;
    _changed();
  }

  void _push(_Snapshot s) {
    _undo.add(s);
    if (_undo.length > undoLimit) {
      _undo.removeAt(0);
    }
    _redo.clear();
  }

  /// Runs [edit] as one undo step; [edit] returns whether it changed
  /// anything (no step is recorded otherwise).
  void _mutate(bool Function() edit) {
    final _Snapshot before = _snapshot();
    if (edit()) {
      _push(before);
      _changed();
    }
  }

  void _changed() {
    _revision++;
    notifyListeners();
  }

