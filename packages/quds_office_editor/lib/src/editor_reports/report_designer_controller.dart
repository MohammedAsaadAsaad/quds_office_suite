  ReportProperty _decorateOne(
    ReportProperty p, {
    required bool element,
    required List<String> formats,
  }) {
    final String leaf = p.key.split('.').last;
    final bool variable = p.key.startsWith('var.');
    if (element && (p.key == 'x' || p.key == 'y')) {
      return p.decorate(pair: true, step: _lengthStep);
    }
    if (element && (p.key == 'width' || p.key == 'height')) {
      return p.decorate(pair: true, step: _lengthStep, min: 0);
    }
    if (p.group == 'Font' &&
        p.kind == ReportPropertyKind.toggle &&
        (leaf == 'bold' || leaf == 'italic' || leaf == 'underline')) {
      return p.decorate(glyph: leaf);
    }
    if (variable && (leaf == 'insert' || leaf == 'remove')) {
      return p.decorate(pair: true);
    }
    if (variable && leaf == 'value') {
      return switch (p.kind) {
        ReportPropertyKind.number => p.decorate(step: 1),
        ReportPropertyKind.text when p.label == 'Date' => p.decorate(
          hint: 'yyyy-MM-dd',
          presets: const <String>['today', 'now'],
        ),
        ReportPropertyKind.text when p.label == 'Items' => p.decorate(
          hint: 'a; b; c',
        ),
        ReportPropertyKind.text => p.decorate(hint: 'text, {{ }} allowed'),
        _ => p,
      };
    }
    if (leaf == 'format' || leaf == 'valueFormat') {
      return p.decorate(hint: 'none', presets: formats);
    }
    if (leaf == 'fontFamily' || leaf == 'defaultFont') {
      return p.decorate(
        hint: leaf == 'defaultFont' ? '' : 'inherit',
        presets: fontFamilies,
      );
    }
    if (leaf == 'fontSize' ||
        leaf == 'headerFontSize' ||
        leaf == 'defaultFontSize') {
      return p.decorate(hint: 'inherit', presets: _fontSizes, step: 1, min: 1);
    }
    if (leaf == 'borderWidth' || leaf == 'strokeWidth') {
      return p.decorate(presets: _strokeWidths, step: 0.25, min: 0);
    }
    if (leaf == 'lineSpacing') {
      return p.decorate(
        presets: const <String>['1', '1.15', '1.5', '2'],
        step: 0.05,
        min: 0.5,
      );
    }
    if (leaf == 'cornerRadius' || leaf == 'padding') {
      return p.decorate(
        step: p.kind == ReportPropertyKind.length ? _lengthStep : 0.5,
        min: 0,
      );
    }
    if (leaf == 'columns') {
      return p.decorate(step: 1, min: 1);
    }
    if (leaf == 'limit' || leaf == 'seriesCount' || leaf == 'pointCount') {
      return p.decorate(step: 1, min: 0);
    }
    if (p.kind == ReportPropertyKind.length) {
      return p.decorate(
        step: _lengthStep,
        min: 0,
        hint: p.value.isEmpty ? 'auto' : null,
      );
    }
    if (p.kind == ReportPropertyKind.color) {
      return p.decorate(hint: 'none');
    }
    return switch (leaf) {
      'visibleWhen' => p.decorate(hint: 'always'),
      'filter' => p.decorate(hint: 'all rows'),
      'sortBy' || 'groupBy' => p.decorate(hint: 'none'),
      'dataSet' => p.decorate(
        hint: primary is ReportChartElement ? 'band rows' : 'none',
      ),
      'name' when element => p.decorate(hint: 'unnamed'),
      'palette' => p.decorate(hint: 'comma separated colors'),
      'description' => p.decorate(hint: 'shown in autocomplete'),
      'color+' => p.decorate(hint: 'name=#RRGGBB'),
      _ => p,
    };
  }

  /// Adds [direction] × the property's step to numeric property [key]
  /// (×10 with [large]), clamped to its minimum. Returns whether it changed.
  bool stepProperty(String key, int direction, {bool large = false}) {
    ReportProperty? p;
    for (final ReportProperty q in properties) {
      if (q.key == key) {
        p = q;
        break;
      }
    }
    final double? step = p?.step;
    if (p == null || step == null || !p.isSteppable) {
      return false;
    }
    final String next = steppedValue(p, direction, large: large);
    if (next == p.value) {
      return false;
    }
    final int before = _revision;
    setProperty(key, next);
    return _revision != before;
  }

  /// [p]'s value moved by one step; keeps the unit suffix of lengths.
  /// [from] replaces the current value (text typed in the inline editor).
  String steppedValue(
    ReportProperty p,
    int direction, {
    bool large = false,
    String? from,
  }) {
    final double base = p.step ?? 1;
    final double step = base * (large ? 10 : 1);
    final RegExpMatch? m = RegExp(
      r'^\s*(-?\d+(?:\.\d+)?)\s*([a-zA-Z"]*)\s*$',
    ).firstMatch(from ?? p.value);
    final String leaf = p.key.split('.').last;
    final double current = m != null
        ? double.parse(m.group(1)!)
        : leaf == 'fontSize' || leaf == 'headerFontSize'
        ? _template.defaultFontSize
        : (double.tryParse(p.hint) ?? p.min ?? 0);
    final String suffix = m?.group(2) ?? '';
    double next = ((current + direction * step) / base).roundToDouble() * base;
    final double? lo = p.min;
    if (lo != null && next < lo) {
      next = lo;
    }
    final String unit = p.kind == ReportPropertyKind.length
        ? (suffix.isEmpty ? _template.unit.suffix : suffix)
        : '';
    return '${ReportUnits.trimNumber(double.parse(next.toStringAsFixed(4)))}$unit';
  }

  /// Sets [key] to [value] on every selected element that has it (else the
  /// selected band, else the report). Invalid values are ignored.
  void setProperty(String key, String value) {
    final RegExpMatch? insert = RegExp(r'^var\.(\d+)\.insert$').firstMatch(key);
    if (insert != null) {
      final int i = int.parse(insert.group(1)!);
      if (i < _template.variables.length) {
        insertVariable(_template.variables[i].name);
      }
      return;
    }
    final List<ReportElement> sel = selectedElements;
    final ReportBand? band = _selectedBand == null
        ? null
        : _template.band(_selectedBand!);
    _mutate(() {
      if (sel.isNotEmpty) {
        var any = false;
        for (final ReportElement e in sel) {
          any = _applyElement(e, key, value) || any;
        }
        return any;
      }
      if (band != null) {
        return _applyBand(band, key, value);
      }
      return _applyReport(key, value);
    });
    notifyListeners();
  }

