/// Pointer tool of the report designer canvas.
enum ReportDesignTool {
  /// Select, move, and resize.
  select,

  /// Draw a text box.
  text,

  /// Draw an image frame.
  image,

  /// Draw a repeating table.
  table,

  /// Draw a Code 128 barcode.
  barcode,

  /// Draw a QR code.
  qr,

  /// Draw a line.
  line,

  /// Draw a rectangle.
  rectangle,

  /// Draw an ellipse.
  ellipse,

  /// Draw a chart.
  chart,
}

/// Alignment and sizing commands for the selection.
enum ReportAlignAction {
  /// Align left edges.
  left,

  /// Align horizontal centers.
  centerX,

  /// Align right edges.
  right,

  /// Align top edges.
  top,

  /// Align vertical centers.
  middle,

  /// Align bottom edges.
  bottom,

  /// Equal horizontal gaps (three or more elements).
  distributeX,

  /// Equal vertical gaps (three or more elements).
  distributeY,

  /// Match the primary element's width.
  sameWidth,

  /// Match the primary element's height.
  sameHeight,
}

/// Designer surface: the band canvas or the paginated live preview.
enum ReportDesignMode {
  /// Band canvas.
  design,

  /// Paginated preview generated by the engine from mock data.
  preview,
}

/// Export target for [ReportDesignerController.export].
enum ReportExportFormat {
  /// PDF document.
  pdf,

  /// Excel workbook.
  xlsx,

  /// Word document.
  docx,
}

/// How the inspector edits a property value.
enum ReportPropertyKind {
  /// Single-line text.
  text,

  /// Multi-line text (template text with placeholders).
  multiline,

  /// Length in the template unit (`12.5mm`).
  length,

  /// Plain number.
  number,

  /// On / off.
  toggle,

  /// One of [ReportProperty.options].
  choice,

  /// Palette name, `#RRGGBB`, or CSS color name.
  color,

  /// Expression without `{{ }}` (`item.qty > 0`).
  expression,

  /// Button; clicking calls [ReportDesignerController.setProperty] with
  /// [ReportProperty.value] as the value.
  action,
}

/// One inspector row. Values are strings so every kind shares one editor;
/// [ReportDesignerController.setProperty] parses them back with type checks.
@immutable
class ReportProperty {
  /// ReportProperty API.
  const ReportProperty({
    required this.key,
    required this.label,
    required this.kind,
    required this.value,
    required this.group,
    this.options = const <String>[],
    this.hint = '',
    this.presets = const <String>[],
    this.step,
    this.min,
    this.pair = false,
    this.glyph,
  });

  /// Stable key passed to [ReportDesignerController.setProperty].
  final String key;

  /// Display label.
  final String label;

  /// Editor kind.
  final ReportPropertyKind kind;

  /// Current value as text (`true`/`false` for toggles).
  final String value;

  /// Section heading.
  final String group;

  /// Allowed values for [ReportPropertyKind.choice].
  final List<String> options;

  /// Shown dimmed when [value] is empty (`auto`, `inherit`, `none`).
  final String hint;

  /// Suggested values for textual kinds (font sizes, format specs); the
  /// user can still type anything.
  final List<String> presets;

  /// Increment of the stepper buttons for numeric kinds (null: no stepper).
  final double? step;

  /// Lowest value the stepper produces.
  final double? min;

  /// Shares a row with the next paired property (X/Y, Width/Height).
  final bool pair;

  /// Toggle drawn as an icon button (`bold`, `italic`, `underline`);
  /// adjacent glyph toggles share one row.
  final String? glyph;

  /// Whether a click opens the inline text editor.
  bool get isTextual =>
      kind != ReportPropertyKind.toggle &&
      kind != ReportPropertyKind.choice &&
      kind != ReportPropertyKind.action;

  /// Whether the value is numeric with a stepper.
  bool get isSteppable =>
      step != null &&
      (kind == ReportPropertyKind.number || kind == ReportPropertyKind.length);

  /// Copy with presentation metadata replaced.
  ReportProperty decorate({
    String? label,
    String? hint,
    List<String>? presets,
    double? step,
    double? min,
    bool? pair,
    String? glyph,
  }) => ReportProperty(
    key: key,
    label: label ?? this.label,
    kind: kind,
    value: value,
    group: group,
    options: options,
    hint: hint ?? this.hint,
    presets: presets ?? this.presets,
    step: step ?? this.step,
    min: min ?? this.min,
    pair: pair ?? this.pair,
    glyph: glyph ?? this.glyph,
  );
}

class _Snapshot {
  _Snapshot(this.template, this.selection, this.band);

  final ReportTemplate template;
  final List<String> selection;
  final ReportBandKind? band;
}

/// State of a report designer: template, selection, undo history, tools,
/// inline editors, and the cached live preview.
///
/// Geometry passed in and out of the "physical" helpers is in page points
/// with x measured from the left page edge, so mirrored RTL templates
/// (`ReportTemplate.mirrored`) edit naturally; the template keeps its
/// authored coordinates.
class ReportDesignerController extends ChangeNotifier {
  /// ReportDesignerController API.
  ReportDesignerController({
    ReportTemplate? template,
    ReportFontRegistry? fonts,
    Map<String, Uint8List>? images,
    Map<String, Object?>? mockData,
    this.clock,
    this.userName = 'Designer',
    this.mockRows = 12,
    this.undoLimit = 100,
  }) : _template = template ?? ReportTemplate(),
       fonts = fonts ?? ReportFontRegistry(),
       images = images ?? <String, Uint8List>{},
       _mockOverride = mockData;

  /// Parses [xml]; throws [ReportTemplateException] when it has errors.
  factory ReportDesignerController.fromXml(
    String xml, {
    ReportFontRegistry? fonts,
    Map<String, Uint8List>? images,
    Map<String, Object?>? mockData,
    DateTime Function()? clock,
  }) => ReportDesignerController(
    template: QudsReportXmlParser().parse(xml).templateOrThrow,
    fonts: fonts,
    images: images,
    mockData: mockData,
    clock: clock,
  );

  ReportTemplate _template;

  /// Fonts used by the preview and exports.
  ReportFontRegistry fonts;

  /// Named images (`<Image source="logo"/>`).
  final Map<String, Uint8List> images;

  /// Clock for `System.CurrentDate` in the preview.
  final DateTime Function()? clock;

  /// `System.UserName` in the preview.
  final String userName;

  /// Rows generated by [ReportMockData.infer] when no data is set.
  int mockRows;

  /// Maximum undo depth.
  final int undoLimit;

  Map<String, Object?>? _mockOverride;
  Map<String, Object?>? _mockInferred;
  int _mockRevision = -1;

  final List<_Snapshot> _undo = <_Snapshot>[];
  final List<_Snapshot> _redo = <_Snapshot>[];
  _Snapshot? _gestureBase;
  var _gestureChanged = false;

  final List<String> _selection = <String>[];
  ReportBandKind? _selectedBand;
  List<ReportElement> _clipboard = <ReportElement>[];
  ReportBandKind? _clipboardBand;

  var _revision = 0;
  ReportDocumentLayout? _preview;
  Object? _previewError;
  int _previewRevision = -1;

  ReportDesignTool _tool = ReportDesignTool.select;
  ReportDesignMode _mode = ReportDesignMode.design;
  double _zoom = 1;

  /// Draw the snap grid.
  var showGrid = true;

  /// Snap moves and resizes to the grid.
  var snapToGrid = true;

  /// Snap to other elements, band edges, and margins.
  var snapToGuides = true;

  /// Grid pitch in points (default 1 mm).
  var gridSize = 72 / 25.4;

  /// Element whose text is being edited on the canvas.
  String? editingId;

  /// IME session for on-canvas text editing.
  late final InlineCellEditor textEditor = InlineCellEditor(
    onCommit: _commitCanvasText,
    onChanged: notifyListeners,
    commitOnNewline: false,
  );

  /// Inspector property being edited, if any.
  String? editingProperty;

  /// IME session for inspector values.
  late final InlineCellEditor propertyEditor = InlineCellEditor(
    onCommit: _commitPropertyText,
    onChanged: notifyListeners,
  );

  ReportCompletionResult? _completion;
  String _completionKey = '';
  String _completionText = '';
  var _completionIndex = 0;
  var _completionForced = false;
  int? _completionDismissedAt;

  static const Set<String> _formatKeys = <String>{'format', 'valueFormat'};

  // ------------------------------------------------------------ completion

  /// Editor the suggestions apply to: the canvas text editor or the
  /// inspector value editor.
  InlineCellEditor? get completionEditor {
    if (editingId != null && textEditor.editing) {
      return textEditor;
    }
    if (editingProperty != null && propertyEditor.editing) {
      return propertyEditor;
    }
    return null;
  }

  /// Suggestions at the caret of [completionEditor], or null.
  ReportCompletionResult? get completion {
    final InlineCellEditor? ed = completionEditor;
    if (ed == null || ed.hasSelection) {
      return null;
    }
    final String text = ed.formulaBar;
    final String key =
        '${editingId ?? ''}|${editingProperty ?? ''}|${ed.caretIndex}|'
        '$_completionForced|${_completionDismissedAt ?? -1}|$text';
    if (key == _completionKey) {
      return _completion;
    }
    if (text != _completionText) {
      _completionIndex = 0;
      _completionText = text;
    }
    _completionKey = key;
    ReportCompletionResult? r = _computeCompletion(ed, text);
    if (r != null && r.start == _completionDismissedAt) {
      r = null;
    } else if (r == null || r.start != _completionDismissedAt) {
      _completionDismissedAt = null;
    }
    if (r == null) {
      _completionForced = false;
    } else if (_completionIndex >= r.items.length) {
      _completionIndex = 0;
    }
    _completion = r;
    return r;
  }

  /// Highlighted suggestion.
  int get completionIndex => _completionIndex;

  ReportCompletionResult? _computeCompletion(InlineCellEditor ed, String text) {
    final ReportBand? band;
    final ReportElement? e = editingId != null
        ? _template.findElement(editingId!)?.$2
        : primary;
    if (e != null) {
      band = _template.findElement(e.id)?.$1;
    } else {
      band = _selectedBand == null ? null : _template.band(_selectedBand!);
    }
    final ReportCompleter completer = ReportCompleter(
      template: _template,
      band: band,
      data: mockData,
    );
    final int caret = ed.caretIndex;
    if (identical(ed, textEditor)) {
      return completer.complete(text, caret, force: _completionForced);
    }
    final String key = editingProperty ?? '';
    ReportPropertyKind? kind;
    for (final ReportProperty p in properties) {
      if (p.key == key) {
        kind = p.kind;
      }
    }
    final String leaf = key.split('.').last;
    if (_formatKeys.contains(leaf)) {
      return completer.completeFormat(text, caret);
    }
    return switch (kind) {
      ReportPropertyKind.expression => completer.complete(
        text,
        caret,
        expression: true,
        force: _completionForced,
      ),
      ReportPropertyKind.text || ReportPropertyKind.multiline =>
        completer.complete(text, caret, force: _completionForced),
      _ => null,
    };
  }

  /// Moves the highlight by [delta] (wraps).
  void moveCompletion(int delta) {
    final ReportCompletionResult? r = completion;
    if (r == null) {
      return;
    }
    final int n = r.items.length;
    _completionIndex = ((_completionIndex + delta) % n + n) % n;
    notifyListeners();
  }

  /// Inserts suggestion [index] (default: the highlighted one).
  bool acceptCompletion([int? index]) {
    final InlineCellEditor? ed = completionEditor;
    final ReportCompletionResult? r = completion;
    if (ed == null || r == null) {
      return false;
    }
    final int i = index ?? _completionIndex;
    if (i < 0 || i >= r.items.length) {
      return false;
    }
    final ReportCompletionItem item = r.items[i];
    _completionForced = false;
    _completionDismissedAt = r.start;
    ed.replaceRange(r.start, r.end, item.insert);
    if (item.caretBack > 0) {
      ed.setCaret(r.start + item.insert.length - item.caretBack);
    }
    return true;
  }

  /// Hides the suggestions until the caret moves to another word.
  void dismissCompletion() {
    final ReportCompletionResult? r = completion;
    if (r == null) {
      return;
    }
    _completionForced = false;
    _completionDismissedAt = r.start;
    notifyListeners();
  }

  /// Shows suggestions even without a typed prefix (Ctrl+Space).
  void triggerCompletion() {
    if (completionEditor == null) {
      return;
    }
    _completionForced = true;
    _completionDismissedAt = null;
    notifyListeners();
  }

  // ------------------------------------------------------------ template

  /// Template being designed (mutated in place by the designer).
  ReportTemplate get template => _template;

  /// Increments on every template change (not on selection changes).
  int get revision => _revision;

  /// Serializes the template.
  String toXml() => const QudsReportXmlWriter().write(_template);

  /// Replaces the template from [xml]; clears history and selection.
  ///
  /// Throws [ReportTemplateException] when [xml] has errors.
  void loadXml(String xml) {
    replaceTemplate(QudsReportXmlParser().parse(xml).templateOrThrow);
  }

  /// Loads a ready-made template with its sample data as preview data.
  void loadTemplate(ReportTemplateInfo info) {
    _mockOverride = info.sampleData();
    _previewRevision = -1;
    loadXml(info.xml);
  }

  /// Replaces the template; clears history and selection.
  void replaceTemplate(ReportTemplate template) {
    _endEdits();
    _template = template;
    _undo.clear();
    _redo.clear();
    _selection.clear();
    _selectedBand = null;
    _changed();
  }

  /// Host data for the preview; null returns to inferred mock data.
  Map<String, Object?> get mockData {
    final Map<String, Object?>? set = _mockOverride;
    if (set != null) {
      return set;
    }
    if (_mockInferred == null || _mockRevision != _revision) {
      _mockInferred = ReportMockData.infer(
        _template,
        rows: mockRows,
        now: clock?.call(),
      );
      _mockRevision = _revision;
    }
    return _mockInferred!;
  }

  set mockData(Map<String, Object?>? data) {
    _mockOverride = data;
    _previewRevision = -1;
    notifyListeners();
  }

  /// Whether [mockData] comes from the host rather than inference.
  bool get hasHostData => _mockOverride != null;

  /// Replaces [fonts] and regenerates the preview.
  void useFonts(ReportFontRegistry registry) {
    fonts = registry;
    _previewRevision = -1;
    notifyListeners();
  }

  /// Engine bound to the current template.
  QudsReportEngine get engine => QudsReportEngine(
    _template,
    fonts: fonts,
    images: images,
    clock: clock,
    userName: userName,
  );

  /// Static template checks (unknown functions, bad expressions).
  List<ReportDiagnostic> validate() => engine.validate();

  /// Live preview of the current template with [mockData], cached per
  /// [revision]. Null when generation failed ([previewError]).
  ReportDocumentLayout? get previewLayout {
    if (_previewRevision != _revision) {
      _previewRevision = _revision;
      try {
        _preview = engine.layout(mockData);
        _previewError = null;
      } on Object catch (e) {
        _preview = null;
        _previewError = e;
      }
    }
    return _preview;
  }

  /// Error raised by the last preview generation.
  Object? get previewError {
    previewLayout;
    return _previewError;
  }

  /// Exports the current template with [mockData].
  Future<Uint8List> export(ReportExportFormat format) {
    final QudsReportEngine e = engine;
    final Map<String, Object?> data = mockData;
    return switch (format) {
      ReportExportFormat.pdf => e.exportToPdf(data),
      ReportExportFormat.xlsx => e.exportToExcel(data),
      ReportExportFormat.docx => e.exportToWord(data),
    };
  }

  // ------------------------------------------------------------ view state

  /// Active pointer tool.
  ReportDesignTool get tool => _tool;

  set tool(ReportDesignTool value) {
    if (_tool == value) {
      return;
    }
    _tool = value;
    notifyListeners();
  }

  /// Canvas or preview.
  ReportDesignMode get mode => _mode;

  set mode(ReportDesignMode value) {
    if (_mode == value) {
      return;
    }
    _endEdits();
    _mode = value;
    notifyListeners();
  }

  /// Switches between canvas and preview.
  void togglePreview() {
    mode = _mode == ReportDesignMode.design
        ? ReportDesignMode.preview
        : ReportDesignMode.design;
  }

  /// Zoom factor (1 = one logical pixel per point).
  double get zoom => _zoom;

  set zoom(double value) {
    final double z = value.clamp(0.25, 4).toDouble();
    if ((z - _zoom).abs() < 1e-6) {
      return;
    }
    _zoom = z;
    notifyListeners();
  }

  /// Width of the canvas viewport in logical pixels (set by the canvas).
  var viewportWidth = 0.0;

  /// Zooms so the page width fills the canvas viewport.
  void fitWidth() {
    if (viewportWidth <= 0) {
      return;
    }
    zoom = (viewportWidth - 48) / _template.pageWidth;
  }

  /// Toggles the grid overlay and grid snapping together.
  void toggleGrid() {
    showGrid = !showGrid;
    snapToGrid = showGrid;
    notifyListeners();
  }

  /// Requests a repaint without changing state (e.g. after an image loads).
  void refresh() => notifyListeners();

  // ------------------------------------------------------------ selection

  /// Selected element ids, primary first.
  List<String> get selection => List<String>.unmodifiable(_selection);

  /// Band selected through its caption (when no element is selected).
  ReportBandKind? get selectedBand => _selectedBand;

  /// Selected elements that still exist, primary first.
  List<ReportElement> get selectedElements => <ReportElement>[
    for (final String id in _selection)
      if (_template.findElement(id) case (_, final ReportElement e)) e,
  ];

  /// First selected element.
  ReportElement? get primary {
    final List<ReportElement> s = selectedElements;
    return s.isEmpty ? null : s.first;
  }

  /// Whether [id] is selected.
  bool isSelected(String id) => _selection.contains(id);

  /// Selects [id] (null clears). [additive] toggles it in the selection.
  void select(String? id, {bool additive = false}) {
    _endEdits();
    if (id == null) {
      if (!additive) {
        _selection.clear();
        _selectedBand = null;
      }
      notifyListeners();
      return;
    }
    if (additive) {
      if (!_selection.remove(id)) {
        _selection.add(id);
      }
    } else if (!(_selection.length > 1 && _selection.contains(id))) {
      _selection
        ..clear()
        ..add(id);
    }
    _selectedBand = _template.findElement(id)?.$1.kind ?? _selectedBand;
    notifyListeners();
  }

  /// Replaces the selection with [ids].
  void selectIds(Iterable<String> ids, {bool additive = false}) {
    _endEdits();
    if (!additive) {
      _selection.clear();
    }
    for (final String id in ids) {
      if (!_selection.contains(id)) {
        _selection.add(id);
      }
    }
    notifyListeners();
  }

  /// Selects a band (clears element selection).
  void selectBand(ReportBandKind? kind) {
    _endEdits();
    _selection.clear();
    _selectedBand = kind;
    notifyListeners();
  }

  /// Selects every element of the selected band, or of the whole report.
  void selectAll() {
    _endEdits();
    _selection.clear();
    final ReportBand? band = _selectedBand == null
        ? null
        : _template.band(_selectedBand!);
    for (final (ReportBand b, ReportElement e) in _template.allElements) {
      if (band == null || identical(b, band)) {
        _selection.add(e.id);
      }
    }
    notifyListeners();
  }

  // ------------------------------------------------------------ geometry

  /// Element box in physical page points; y is relative to its band.
  ReportRect physicalRect(ReportElement e) =>
      ReportRect(_template.elementLeft(e.x, e.width), e.y, e.width, e.height);

  void _setPhysical(ReportElement e, ReportRect r) {
    final double w = r.width < 0 ? 0 : r.width;
    final double h = r.height < 0 ? 0 : r.height;
    e
      ..width = _round(w)
      ..height = _round(h)
      ..x = _round(_template.elementX(r.left, w))
      ..y = _round(r.top < 0 ? 0 : r.top);
  }

  static double _round(double v) => (v * 100).roundToDouble() / 100;

  /// Starts a pointer gesture; edits until [endGesture] form one undo step.
  void beginGesture() {
    _endEdits();
    _gestureBase = _snapshot();
    _gestureChanged = false;
  }

  /// Moves or resizes elements during a gesture (physical, band-relative).
  void gestureSetRects(Map<String, ReportRect> rects) {
    for (final MapEntry<String, ReportRect> entry in rects.entries) {
      final ReportElement? e = _template.findElement(entry.key)?.$2;
      if (e != null) {
        _setPhysical(e, entry.value);
      }
    }
    _gestureChanged = true;
    _changed();
  }

  /// Resizes a band during a gesture.
  void gestureSetBandHeight(ReportBandKind kind, double height) {
    final ReportBand? band = _template.band(kind);
    if (band == null) {
      return;
    }
    band.height = _round(height < 0 ? 0 : height);
    _gestureChanged = true;
    _changed();
  }

  /// Moves element [id] into band [target] at band-relative [top].
  void gestureMoveToBand(String id, ReportBandKind target, double top) {
    final (ReportBand, ReportElement)? found = _template.findElement(id);
    final ReportBand? to = _template.band(target);
    if (found == null || to == null || identical(found.$1, to)) {
      return;
    }
    found.$1.elements.remove(found.$2);
    to.elements.add(found.$2);
    found.$2.y = _round(top < 0 ? 0 : top);
    if (to.height < found.$2.y + found.$2.height) {
      to.height = _round(found.$2.y + found.$2.height);
    }
    _selectedBand = target;
    _gestureChanged = true;
    _changed();
  }

  /// Ends the gesture started by [beginGesture].
  void endGesture() {
    final _Snapshot? base = _gestureBase;
    _gestureBase = null;
    if (base != null && _gestureChanged) {
      _push(base);
    }
    _gestureChanged = false;
    notifyListeners();
  }

  /// Moves the selection by ([dx], [dy]) physical points.
  void nudge(double dx, double dy) {
    final List<ReportElement> sel = selectedElements;
    if (sel.isEmpty) {
      return;
    }
    _mutate(() {
      for (final ReportElement e in sel) {
        final ReportRect r = physicalRect(e);
        _setPhysical(e, ReportRect(r.left + dx, r.top + dy, r.width, r.height));
      }
      return true;
    });
  }

  /// Applies [action] to the selection. With one element, aligns to the
  /// band (vertical) and the printable area (horizontal).
  void align(ReportAlignAction action) {
    final List<ReportElement> sel = selectedElements;
    if (sel.isEmpty) {
      return;
    }
    final List<ReportRect> rects = <ReportRect>[
      for (final ReportElement e in sel) physicalRect(e),
    ];
    double left;
    double top;
    double right;
    double bottom;
    if (sel.length == 1) {
      final ReportBand band = _template.findElement(sel.first.id)!.$1;
      left = _template.margins.left;
      right = _template.pageWidth - _template.margins.right;
      top = 0;
      bottom = band.designHeight;
    } else {
      left = rects.map((ReportRect r) => r.left).reduce(_min);
      top = rects.map((ReportRect r) => r.top).reduce(_min);
      right = rects.map((ReportRect r) => r.right).reduce(_max);
      bottom = rects.map((ReportRect r) => r.bottom).reduce(_max);
    }
    final ReportRect lead = rects.first;
    _mutate(() {
      switch (action) {
        case ReportAlignAction.distributeX:
        case ReportAlignAction.distributeY:
          return _distribute(
            sel,
            rects,
            action == ReportAlignAction.distributeX,
          );
        default:
          break;
      }
      for (int i = 0; i < sel.length; i++) {
        final ReportRect r = rects[i];
        final ReportRect next = switch (action) {
          ReportAlignAction.left => ReportRect(left, r.top, r.width, r.height),
          ReportAlignAction.right => ReportRect(
            right - r.width,
            r.top,
            r.width,
            r.height,
          ),
          ReportAlignAction.centerX => ReportRect(
            (left + right - r.width) / 2,
            r.top,
            r.width,
            r.height,
          ),
          ReportAlignAction.top => ReportRect(r.left, top, r.width, r.height),
          ReportAlignAction.bottom => ReportRect(
            r.left,
            bottom - r.height,
            r.width,
            r.height,
          ),
          ReportAlignAction.middle => ReportRect(
            r.left,
            (top + bottom - r.height) / 2,
            r.width,
            r.height,
          ),
          ReportAlignAction.sameWidth => ReportRect(
            r.left,
            r.top,
            lead.width,
            r.height,
          ),
          ReportAlignAction.sameHeight => ReportRect(
            r.left,
            r.top,
            r.width,
            lead.height,
          ),
          ReportAlignAction.distributeX || ReportAlignAction.distributeY => r,
        };
        _setPhysical(sel[i], next);
      }
      return true;
    });
  }

  bool _distribute(
    List<ReportElement> sel,
    List<ReportRect> rects,
    bool horizontal,
  ) {
    if (sel.length < 3) {
      return false;
    }
    final List<int> order = List<int>.generate(sel.length, (int i) => i)
      ..sort(
        (int a, int b) => horizontal
            ? rects[a].left.compareTo(rects[b].left)
            : rects[a].top.compareTo(rects[b].top),
      );
    final ReportRect first = rects[order.first];
    final ReportRect last = rects[order.last];
    var occupied = 0.0;
    for (final ReportRect r in rects) {
      occupied += horizontal ? r.width : r.height;
    }
    final double span = horizontal
        ? last.right - first.left
        : last.bottom - first.top;
    final double gap = (span - occupied) / (sel.length - 1);
    var cursor = horizontal ? first.left : first.top;
    for (final int i in order) {
      final ReportRect r = rects[i];
      _setPhysical(
        sel[i],
        horizontal
            ? ReportRect(cursor, r.top, r.width, r.height)
            : ReportRect(r.left, cursor, r.width, r.height),
      );
      cursor += (horizontal ? r.width : r.height) + gap;
    }
    return true;
  }

  static double _min(double a, double b) => a < b ? a : b;

  static double _max(double a, double b) => a > b ? a : b;

