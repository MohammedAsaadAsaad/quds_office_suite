  /// Creates an element for [tool] in [band] at physical, band-relative
  /// [rect]. A tiny rect gets the tool's default size. Selects it.
  ReportElement? addElement(
    ReportDesignTool tool,
    ReportBandKind band,
    ReportRect rect,
  ) {
    if (tool == ReportDesignTool.select) {
      return null;
    }
    final ReportBand? target = _template.band(band);
    if (target == null) {
      return null;
    }
    final ReportElement e = _newElement(tool, target);
    final bool tiny = rect.width < 4 && rect.height < 4;
    final double w = tiny ? e.width : rect.width;
    final double h = tiny
        ? e.height
        : (tool == ReportDesignTool.line && rect.height < 3 ? 0 : rect.height);
    final double left = tiny && _template.mirrored ? rect.left - w : rect.left;
    _mutate(() {
      target.elements.add(e);
      _setPhysical(e, ReportRect(left, rect.top, w, h));
      if (target.height < e.y + e.height) {
        target.height = _round(e.y + e.height);
      }
      return true;
    });
    _selection
      ..clear()
      ..add(e.id);
    _selectedBand = band;
    notifyListeners();
    return e;
  }

