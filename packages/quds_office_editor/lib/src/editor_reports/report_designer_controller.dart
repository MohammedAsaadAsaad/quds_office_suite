  static final RegExp _variableName = RegExp(
    r'^[A-Za-z_\u0600-\u06FF][A-Za-z0-9_\u0600-\u06FF]*$',
  );

  ReportVariable _newVariable(
    ReportTemplate t, {
    String? name,
    ReportVariableType type = ReportVariableType.text,
    String? value,
  }) {
    bool taken(String n) => t.variables.any(
      (ReportVariable o) => o.name.toLowerCase() == n.toLowerCase(),
    );
    var candidate = name ?? 'variable1';
    var n = 1;
    while (taken(candidate)) {
      n++;
      candidate = '${name ?? 'variable'}$n';
    }
    final ReportVariable v = ReportVariable(
      name: candidate,
      type: type,
      value: value ?? _variableDefault(type),
    );
    t.variables.add(v);
    return v;
  }

  bool _applyVariable(ReportTemplate t, String key, String v) {
    final List<String> parts = key.split('.');
    final int? i = parts.length == 3 ? int.tryParse(parts[1]) : null;
    if (i == null || i < 0 || i >= t.variables.length) {
      return false;
    }
    final ReportVariable x = t.variables[i];
    switch (parts[2]) {
      case 'name':
        final String n = v.trim();
        if (n == x.name ||
            !_variableName.hasMatch(n) ||
            t.variables.any(
              (ReportVariable o) =>
                  !identical(o, x) && o.name.toLowerCase() == n.toLowerCase(),
            )) {
          return false;
        }
        final String old = x.name;
        x.name = n;
        _renameVariableRefs(old, n);
      case 'type':
        final ReportVariableType? type = reportEnumByName(
          ReportVariableType.values,
          v,
        );
        if (type == null || type == x.type) {
          return false;
        }
        x.type = type;
        if (x.error != null) {
          x.value = _variableDefault(type);
        }
      case 'value':
        final String old = x.value;
        x.value = x.type == ReportVariableType.text ? v : v.trim();
        if (x.error != null) {
          x.value = old;
          return false;
        }
      case 'format':
        x.format = _opt(v);
      case 'description':
        x.description = v.trim();
      case 'remove':
        t.variables.removeAt(i);
      default:
        return false;
    }
    return true;
  }

  /// Rewrites `Variables.old` references after a rename.
  void _renameVariableRefs(String old, String now) {
    final String xml = toXml();
    final RegExp ref = RegExp(
      '(?<![A-Za-z0-9_.\u0600-\u06FF])((?:Variables|Vars|Var)\\.)'
      '${RegExp.escape(old)}(?![A-Za-z0-9_\u0600-\u06FF])',
      caseSensitive: false,
      unicode: true,
    );
    if (!ref.hasMatch(xml)) {
      return;
    }
    final String renamed = xml.replaceAllMapped(
      ref,
      (Match m) => '${m.group(1)}$now',
    );
    final ReportParseResult parsed = QudsReportXmlParser().parse(renamed);
    if (parsed.hasErrors) {
      return;
    }
    _template = parsed.templateOrThrow;
    _selection.clear();
  }

  /// Adds a template variable and returns it (unique [name], default value
  /// for [type]). Undoable.
  ReportVariable addVariable({
    String? name,
    ReportVariableType type = ReportVariableType.text,
    String? value,
  }) {
    late ReportVariable added;
    _mutate(() {
      added = _newVariable(_template, name: name, type: type, value: value);
      return true;
    });
    return added;
  }

  /// Inserts `{{Variables.name}}` (with its format): at the caret while
  /// editing text or an inspector value (bare `Variables.name` in
  /// expressions), else as a new text box in the selected band. Returns the
  /// created element, if any.
  ReportElement? insertVariable(String name) {
    ReportVariable? v;
    for (final ReportVariable x in _template.variables) {
      if (x.name.toLowerCase() == name.toLowerCase()) {
        v = x;
      }
    }
    if (v == null) {
      return null;
    }
    if (editingId != null && textEditor.editing) {
      textEditor.replaceRange(
        textEditor.selectionStart,
        textEditor.selectionEnd,
        v.placeholder,
      );
      return null;
    }
    if (editingProperty != null && propertyEditor.editing) {
      ReportPropertyKind? kind;
      for (final ReportProperty p in properties) {
        if (p.key == editingProperty) {
          kind = p.kind;
        }
      }
      propertyEditor.replaceRange(
        propertyEditor.selectionStart,
        propertyEditor.selectionEnd,
        kind == ReportPropertyKind.expression
            ? 'Variables.${v.name}'
            : v.placeholder,
      );
      return null;
    }
    ReportBandKind? kind = _selectedBand;
    final ReportElement? p = primary;
    if (p != null) {
      kind = _template.findElement(p.id)?.$1.kind;
    }
    if (kind == null || _template.band(kind) == null) {
      kind = null;
      for (final ReportBandKind k in const <ReportBandKind>[
        ReportBandKind.reportHeader,
        ReportBandKind.pageHeader,
        ReportBandKind.detail,
      ]) {
        if (kind == null && _template.band(k) != null) {
          kind = k;
        }
      }
      kind ??= _template.bands.isEmpty ? null : _template.bands.first.kind;
    }
    if (kind == null) {
      addBand(ReportBandKind.reportHeader);
      kind = ReportBandKind.reportHeader;
    }
    final ReportBand band = _template.band(kind)!;
    var top = 0.0;
    for (final ReportElement e in band.elements) {
      top = _max(top, e.y + e.height);
    }
    final ReportTemplate t = _template;
    final double left = t.mirrored
        ? t.pageWidth - t.margins.right
        : t.margins.left;
    final ReportElement? e = addElement(
      ReportDesignTool.text,
      kind,
      ReportRect(left, top, 0, 0),
    );
    if (e is ReportTextElement) {
      e.text = v.placeholder;
      _changed();
    }
    return e;
  }

  bool _applyElement(ReportElement e, String key, String v) {
    switch (key) {
      case 'name':
        e.name = _opt(v);
        return true;
      case 'visibleWhen':
        e.visibleWhen = _opt(v);
        return true;
      case 'x' || 'y' || 'width' || 'height':
        final double? n = _parseLen(v);
        if (n == null || (n < 0 && key != 'x')) {
          return false;
        }
        switch (key) {
          case 'x':
            e.x = _round(n);
