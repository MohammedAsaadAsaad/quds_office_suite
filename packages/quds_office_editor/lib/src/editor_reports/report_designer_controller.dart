            e.y = _round(n);
          case 'width':
            e.width = _round(n);
          default:
            e.height = _round(n);
        }
        return true;
    }
    return switch (e) {
      ReportTextElement() => _applyText(e, key, v),
      ReportImageElement() => _applyImage(e, key, v),
      ReportBarcodeElement() => _applyBarcode(e, key, v),
      ReportShapeElement() => _applyShape(e, key, v),
      ReportTableElement() => _applyTable(e, key, v),
      ReportChartElement() => _applyChart(e, key, v),
    };
  }

